/*

Assigning the Value of One Variable to Another

After a value is assigned to a variable using the assignment operator, you can assign the
value of that variable to another variable using the assignment operator.

*/

var myVar;
myVar = 5;
var myNum;
myNum = myVar;

/*

The above declare a myVar variable with no value, then assigns it to the value 5.
Next, a variable named myNum is declared with no value. Then, the contents of myVar (which is
now 5) is assigned to the variable myNum.

Now, myNum also has the value of 5.

*/